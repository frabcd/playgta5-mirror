import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const source=readFileSync('out/_worker.js','utf8');
assert(!source.includes(process.env.GTA_PASSWORD));
const {default:worker}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
const origin='https://fran-abcd-abcd.pages.dev';
const env={ASSETS:{fetch:async request=>new Response(new URL(request.url).pathname)}};
const run=request=>worker.fetch(request,env);
const login=password=>new Request(origin+'/api/game-unlock',{method:'POST',headers:{Origin:origin,'Content-Type':'application/json'},body:JSON.stringify({password})});
assert.equal((await run(login('incorrect'))).status,401);
assert.equal((await run(new Request(origin+'/api/game-unlock',{method:'POST',headers:{Origin:'https://other.example'},body:'{}'}))).status,403);
assert.equal((await run(new Request(origin+'/calculator/gta-v/play'))).status,303);
assert.equal((await run(new Request(origin+'/calculator/gta-v/frame'))).status,303);
assert.equal((await run(new Request(origin+'/chunk-index.js'))).status,401);
const response=await run(login(process.env.GTA_PASSWORD));
assert.equal(response.status,200);
const cookie=response.headers.get('Set-Cookie');
assert.match(cookie,/Path=\/; Max-Age=28800; HttpOnly; Secure; SameSite=Strict/);
const session=cookie.split(';')[0];
const game=await run(new Request(origin+'/calculator/gta-v/play',{headers:{Cookie:session}}));
assert.equal(game.status,200);
assert.match(await game.text(),/src="\/calculator\/gta-v\/frame[?]/);
assert.equal((await run(new Request(origin+'/calculator/gta-v/play',{headers:{Cookie:session+'tamper'}}))).status,303);
let forwardedHeaders,forwardedUrl;
globalThis.fetch=async(url,options)=>{forwardedHeaders=options.headers;forwardedUrl=String(url);return new Response('<html><head></head><body>game</body></html>',{headers:{'Content-Type':'text/html','X-Frame-Options':'DENY','Content-Security-Policy':"frame-ancestors 'none'"}})};
const frame=await run(new Request(origin+'/calculator/gta-v/frame?low=1',{headers:{Cookie:session}}));
assert.equal(frame.status,200);
assert.match(await frame.text(),/<base href="\/">/);
assert.equal(frame.headers.get('X-Frame-Options'),'SAMEORIGIN');
assert.equal(frame.headers.get('Content-Security-Policy'),"frame-ancestors 'self'");
assert.equal(forwardedHeaders.has('Cookie'),false);
assert.equal(forwardedUrl,'https://9104c0b6.fran-abcd-abcd.pages.dev/?low=1');
await run(new Request(origin+'/b/build/game.wasm',{headers:{Cookie:session,Range:'bytes=0-3'}}));
assert.equal(forwardedHeaders.get('Range'),'bytes=0-3');
assert.equal(await (await run(new Request(origin+'/'))).text(),'/');
assert.equal(await (await run(new Request(origin+'/calculator/gta-v/'))).text(),'/gta-login');
console.log('Password, session, same-origin frame, anonymous-resource rejection, Range and cookie-isolation checks passed.');
